fn compress(h: &mut [u32; 4], block: &[u8]) {
    let mut m = [0u32; 16];
    for i in 0..16 {
        m[i] = u32::from_le_bytes([block[4 * i], block[4 * i + 1], block[4 * i + 2], block[4 * i + 3]]);
    }
    let (mut a, mut b, mut c, mut d) = (h[0], h[1], h[2], h[3]);
    for i in 0..64 {
        let (f, g) = match i {
            0..=15 => ((b & c) | ((!b) & d), i),
            16..=31 => ((d & b) | ((!d) & c), (5 * i + 1) % 16),
            32..=47 => (b ^ c ^ d, (3 * i + 5) % 16),
            _ => (c ^ (b | !d), (7 * i) % 16),
        };
        let tmp = d;
        d = c;
        c = b;
        let sum = a.wrapping_add(f).wrapping_add(T[i]).wrapping_add(m[g]);
        b = b.wrapping_add(sum.rotate_left(S[i]));
        a = tmp;
    }
    h[0] = h[0].wrapping_add(a);
    h[1] = h[1].wrapping_add(b);
    h[2] = h[2].wrapping_add(c);
    h[3] = h[3].wrapping_add(d);
}

pub fn digest(data: &[u8]) -> [u8; 16] {
    let mut h: [u32; 4] = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476];
    let mut off = 0;
    while off + 64 <= data.len() {
        compress(&mut h, &data[off..off + 64]);
        off += 64;
    }
    let rem = &data[off..];
    let bits = (data.len() as u64).wrapping_mul(8);
    let mut buf = [0u8; 128];
    buf[..rem.len()].copy_from_slice(rem);
    buf[rem.len()] = 0x80;
    let total = if rem.len() < 56 { 64 } else { 128 };
    buf[total - 8..total].copy_from_slice(&bits.to_le_bytes());
    compress(&mut h, &buf[..64]);
    if total == 128 {
        compress(&mut h, &buf[64..128]);
    }
    let mut out = [0u8; 16];
    for i in 0..4 {
        out[4 * i..4 * i + 4].copy_from_slice(&h[i].to_le_bytes());
    }
    out
}
