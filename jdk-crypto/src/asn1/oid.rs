/// 摘要 OID -> 算法名后缀（`SHA256` -> `SHA256withRSA` 的拼装用）。
pub fn digest_alg_name(oid: &[u8]) -> Option<&'static str> {
    Some(match oid {
        MD5 => "MD5",
        SHA1 => "SHA1",
        SHA256 => "SHA256",
        SHA384 => "SHA384",
        SHA512 => "SHA512",
        _ => return None,
    })
}
